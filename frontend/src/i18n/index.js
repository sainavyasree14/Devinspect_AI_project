// Read persisted language before init — ensures correct language on first render
const savedLang = (() => {
  try { return localStorage.getItem('devinspect-lang') || 'en'; } catch { return 'en'; }
})();

i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources: {
      en: { translation: en },
      hi: { translation: hi },
      te: { translation: te },
    },
    lng: savedLang,           // use saved language immediately — no flicker
    fallbackLng: 'en',
    interpolation: { escapeValue: false },
    detection: {
      // Disable auto-detection — we manage language manually
      order: [],
    },
  });

export default i18n;
